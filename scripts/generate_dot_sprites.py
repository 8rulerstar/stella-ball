def mirror_x(frame):
    return ["".join(reversed(line)) for line in frame]


def mirror_y(frame):
    return list(reversed(frame))


def bake(name, frames, palette, cell):
    rows = len(frames[0])
    cols = len(frames[0][0])
    img = Image.new("RGBA", (cols * cell * len(frames), rows * cell), (0, 0, 0, 0))
    px = img.load()
    for fi, frame in enumerate(frames):
        assert len(frame) == rows, f"{name} F{fi} 행수가 {len(frame)}"
        for row, line in enumerate(frame):
            assert len(line) == cols, f"{name} F{fi} {row}행이 {len(line)}칸"
            for col, ch in enumerate(line):
                if ch == ".":
                    continue
                hexv = palette[ch]
                rgb = tuple(int(hexv[i : i + 2], 16) for i in (1, 3, 5)) + (255,)
                for dy in range(cell):
                    for dx in range(cell):
                        px[(fi * cols + col) * cell + dx, row * cell + dy] = rgb
    return img


def save(img, rel):
    path = ROOT / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    img.save(path)
    print(f"  {path}  {img.size[0]}x{img.size[1]}")
    return rel


